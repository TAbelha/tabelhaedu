export const MAX_UPLOAD_BYTES = 5 * 1024 * 1024;

// SVG is excluded on purpose: it can embed scripts.
const EXTENSIONS = {
	'image/png': 'png',
	'image/jpeg': 'jpg',
	'image/webp': 'webp',
	'image/gif': 'gif'
} as const;

export type MediaExt = (typeof EXTENSIONS)[keyof typeof EXTENSIONS];

export const CONTENT_TYPES: Record<MediaExt, string> = {
	png: 'image/png',
	jpg: 'image/jpeg',
	webp: 'image/webp',
	gif: 'image/gif'
};

export function validateUpload(f: {
	type: string;
	size: number;
}): { ok: true; ext: MediaExt } | { ok: false; reason: 'type' | 'size' } {
	const ext = EXTENSIONS[f.type as keyof typeof EXTENSIONS];
	if (!ext) return { ok: false, reason: 'type' };
	if (f.size > MAX_UPLOAD_BYTES) return { ok: false, reason: 'size' };
	return { ok: true, ext };
}

// Keys are generated by storeMedia; anything else is rejected before touching R2.
export const MEDIA_KEY_PATTERN = /^org\/[\w-]+\/[0-9a-f-]{36}\.(png|jpg|webp|gif)$/;
