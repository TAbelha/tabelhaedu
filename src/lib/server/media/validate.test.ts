import { describe, expect, it } from 'vitest';
import { MAX_UPLOAD_BYTES, MEDIA_KEY_PATTERN, validateUpload } from './validate';

describe('validateUpload', () => {
	it('accepts a small png', () => {
		expect(validateUpload({ type: 'image/png', size: 1024 })).toEqual({ ok: true, ext: 'png' });
	});

	it('rejects svg, which can carry scripts', () => {
		expect(validateUpload({ type: 'image/svg+xml', size: 1024 })).toEqual({
			ok: false,
			reason: 'type'
		});
	});

	it('rejects files over the size limit', () => {
		expect(validateUpload({ type: 'image/jpeg', size: MAX_UPLOAD_BYTES + 1 })).toEqual({
			ok: false,
			reason: 'size'
		});
	});

	it('rejects a missing type', () => {
		expect(validateUpload({ type: '', size: 10 })).toEqual({ ok: false, reason: 'type' });
	});
});

describe('MEDIA_KEY_PATTERN', () => {
	it('accepts keys generated by storeMedia', () => {
		expect(MEDIA_KEY_PATTERN.test('org/org-a/0b6f1c2e-8a4d-4f7e-9c1a-2d3e4f5a6b7c.png')).toBe(true);
	});

	it('rejects other keys', () => {
		expect(MEDIA_KEY_PATTERN.test('org/org-a/../secret.png')).toBe(false);
		expect(MEDIA_KEY_PATTERN.test('other/x.png')).toBe(false);
		expect(MEDIA_KEY_PATTERN.test('org/org-a/0b6f1c2e-8a4d-4f7e-9c1a-2d3e4f5a6b7c.svg')).toBe(
			false
		);
	});
});
